"""Pre-formatted figures for the run. Claude cites these; it never computes its own."""

from __future__ import annotations

from collections import Counter, defaultdict
from decimal import Decimal

from cashapp.config import Config
from cashapp.data import Inputs
from cashapp.matching import AUTO, EXCEPTION, Plan, Result
from cashapp.money import ZERO, D, fmt


def _pct(a: Decimal | int, b: Decimal | int) -> str:
    return f"{(Decimal(a) / Decimal(b) * 100):.1f}%" if b else "0.0%"


def figures(
    results: list[Result],
    inputs: Inputs,
    cfg: Config,
    plans: dict[str, Plan] | None = None,
    ar_rows: list[dict] | None = None,
) -> dict:
    deps = inputs.deposits
    total = sum((d.amount for d in deps), ZERO)
    auto = [r for r in results if r.status == AUTO]
    exc = [r for r in results if r.status == EXCEPTION]
    auto_amt = sum((r.deposit.amount for r in auto), ZERO)
    exc_amt = sum((r.deposit.amount for r in exc), ZERO)
    by_type: dict[str, list[Result]] = defaultdict(list)
    for r in exc:
        by_type[r.exception_type].append(r)
    rules = Counter(r.rule for r in auto)

    f: dict = {
        "company": cfg.company,
        "value_date": inputs.value_date,
        "deposit_count": len(deps),
        "deposit_total": f"{total:.2f}",
        "auto_count": len(auto),
        "auto_amount": f"{auto_amt:.2f}",
        "auto_rate_count_pct": _pct(len(auto), len(deps)),
        "auto_rate_value_pct": _pct(auto_amt, total),
        "exception_count": len(exc),
        "exception_amount": f"{exc_amt:.2f}",
        "auto_by_rule": dict(sorted(rules.items())),
        "exceptions_by_type": {
            t: {
                "count": len(rs),
                "amount": f"{sum((r.deposit.amount for r in rs), ZERO):.2f}",
            }
            for t, rs in sorted(by_type.items())
        },
    }
    if plans is not None:
        adj: dict[str, Decimal] = defaultdict(lambda: ZERO)
        for p in plans.values():
            for a in p.adjustments:
                adj[a.kind] += a.amount
        applied = sum((p.applied for p in plans.values()), ZERO)
        on_acct = sum((p.on_account for p in plans.values()), ZERO)
        unapplied = sum((p.unapplied for p in plans.values()), ZERO)
        f.update(
            {
                "cash_applied": f"{applied:.2f}",
                "on_account": f"{on_acct:.2f}",
                "left_unapplied": f"{unapplied:.2f}",
                "left_unapplied_count": sum(1 for p in plans.values() if p.unapplied > 0),
                "applied_rate_value_pct": _pct(applied + on_acct, total),
                "deductions_reclassed": f"{adj['DEDUCTION_RECLASS']:.2f}",
                "small_balance_writeoffs": f"{adj['SMALL_BALANCE']:.2f}",
                "bank_fees": f"{adj['BANK_FEE']:.2f}",
            }
        )
    if ar_rows is not None:
        f["docs_touched"] = len(ar_rows)
        f["docs_closed"] = sum(1 for r in ar_rows if r["status_after"] == "CLOSED")
        f["ar_relieved"] = (
            f"{sum((D(r['cash_applied']) + D(r['adjustments']) for r in ar_rows), ZERO):.2f}"
        )
    return f


def facts_md(f: dict, results: list[Result], resolutions: dict | None = None) -> str:
    m = lambda k: fmt(D(f[k]))  # noqa: E731
    out = [
        f"# Facts: {f['company']} cash application, {f['value_date']}",
        "",
        "Every figure the summary may cite. Generated by Python; do not edit.",
        "",
        "## Batch",
        f"- Deposits: {f['deposit_count']} totaling {m('deposit_total')}",
        f"- Auto-matched: {f['auto_count']} deposits, {m('auto_amount')} "
        f"({f['auto_rate_count_pct']} by count, {f['auto_rate_value_pct']} by value)",
        f"- Exceptions: {f['exception_count']} deposits, {m('exception_amount')}",
        "",
        "## Auto-matches by rule",
    ]
    out += [f"- {k}: {v}" for k, v in f["auto_by_rule"].items()]
    out += ["", "## Exceptions by type"]
    out += [
        f"- {t}: {v['count']} ({fmt(D(v['amount']))})" for t, v in f["exceptions_by_type"].items()
    ]
    out += ["", "## Exceptions"]
    for r in results:
        if r.status != EXCEPTION:
            continue
        chosen = ""
        if resolutions and r.exception_id in resolutions:
            chosen = f" -> {resolutions[r.exception_id]}"
        out.append(
            f"- {r.exception_id}: {r.exception_type}, {r.deposit.payer_name}, "
            f"{fmt(r.deposit.amount)}{chosen}"
        )
    if "cash_applied" in f:
        out += [
            "",
            "## After recommended resolutions (pending approval)",
            f"- Cash applied to open items: {m('cash_applied')}",
            f"- On-account credits: {m('on_account')}",
            f"- Left in Unapplied Cash: {m('left_unapplied')} "
            f"({f['left_unapplied_count']} deposits)",
            f"- Applied or on account, share of batch value: {f['applied_rate_value_pct']}",
            f"- Deductions moved to 120300 for validation: {m('deductions_reclassed')}",
            f"- Small-balance write-offs: {m('small_balance_writeoffs')}",
            f"- Wire bank fees: {m('bank_fees')}",
        ]
    if "docs_touched" in f:
        out += [
            f"- AR items touched: {f['docs_touched']}; closed: {f['docs_closed']}",
            f"- AR relieved (cash + adjustments): {m('ar_relieved')}",
        ]
    return "\n".join(out) + "\n"
